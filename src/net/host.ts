// NetHost — the authoritative side of an online duel (the player who created the room). No Phaser: the duel
// screen drives it through src/net/remote.ts, tests drive it directly.
//
//   const host = new NetHost(transport, { name, deck, arena });
//   await host.open(roomIdFor(code));         // waits in the room
//   host.onStatus = (s) => ...;               // 'waiting' → 'ready' (a guest said hello) → 'playing' ...
//   const opening = host.startGame();         // newGame (host = player 0, guest = player 1), sends `start`
//   // each turn: the host's own actions and the guest's intents (takeIntent) are applied by the caller with the
//   // engine, then committed:
//   host.commit(result, actor);               // broadcasts the filtered update
//   host.refuse(intent, reason);              // an illegal intent: nack
//
// Hidden information: the guest only ever receives viewFor(state, 1) / viewEvents(events, 1). Deck lists are
// shuffled with a secret random before newGame, so uids (assigned in list order) say nothing about the cards,
// and the seed never leaves the host.

import { isFusionMonster, type CardId } from '../data/cards';
import { validateDeck } from '../data/decks';
import { actingPlayer, isLegal, legalActions, newGame, viewEvents, viewFor } from '../engine';
import type { Action, ApplyResult, GameState, NewGameOptions, PlayerId } from '../engine/types';
import { DISCONNECT_TIMEOUT_MS, PING_MS, SILENCE_MS } from './config';
import { PROTOCOL_VERSION, decode, encode, gameVersion, type ArenaId, type NetMessage } from './protocol';
import { cryptoRandom } from './roomCode';
import type { NetTransport } from './transport';

export type HostStatus = 'idle' | 'waiting' | 'ready' | 'playing' | 'disconnected' | 'over' | 'closed';

export const HOST_PLAYER: PlayerId = 0;
export const GUEST_PLAYER: PlayerId = 1;

export interface HostOpts {
  name?: string;
  /** The host's deck (card ids, Fusion Monsters included). */
  deck: CardId[];
  arena?: ArenaId;
  /** Extra newGame options (zones, opening hand...). */
  game?: Omit<NewGameOptions, 'seed' | 'decks'>;
  /** Fixed seed (tests). Default: crypto random. */
  seed?: number;
  /** Secret random for the deck-list shuffle (tests). */
  rand?: () => number;
  /** Version string compared with the guest's (default gameVersion()). */
  version?: string;
  disconnectTimeoutMs?: number;
  /** Keep-alive (ms, 0 = off: tests). */
  pingMs?: number;
}

export interface GuestIntent {
  seq: number;
  action: Action;
  /** Generated by the host itself (timeout surrender): skip the legality check. */
  trusted?: boolean;
}

export class NetHost {
  readonly opts: HostOpts;
  status: HostStatus = 'idle';
  /** Session id of the running game (a reconnecting guest names it). */
  session = '';
  state: GameState | null = null;
  /** Number of applied actions (the state's sequence number). */
  seq = 0;
  guestName = 'FRIEND';
  guestDeck: CardId[] | null = null;
  /** Round-trip time of the last ping (ms). */
  rtt = 0;
  onStatus: ((s: HostStatus, why?: string) => void) | null = null;
  /** A guest intent arrived (the duel loop wakes up and takes it). */
  onIntent: (() => void) | null = null;
  /** The guest stayed away longer than the timeout (the caller ends the duel). */
  onTimeout: (() => void) | null = null;
  /** The guest left the duel for good (quit). */
  onGuestLeft: (() => void) | null = null;
  readonly transport: NetTransport;
  private guestPeer: string | null = null;
  private intents: GuestIntent[] = [];
  private timeout: ReturnType<typeof setTimeout> | null = null;
  private ping: ReturnType<typeof setInterval> | null = null;
  private lastHeard = 0;
  private readonly version: string;
  /** Guest-filtered copy of the last update (re-sent on resync). */
  private names: [string, string];

  constructor(transport: NetTransport, opts: HostOpts) {
    this.transport = transport;
    this.opts = opts;
    this.version = opts.version ?? gameVersion();
    this.names = [opts.name ?? 'HOST', 'FRIEND'];
    transport.onMessage = (text, peer) => this.receive(text, peer);
    transport.onPeerJoin = () => undefined; // the guest speaks first (hello)
    transport.onPeerLeave = (peer) => {
      if (peer === this.guestPeer) this.lost('peer left');
    };
  }

  async open(roomId: string): Promise<void> {
    await this.transport.connect(roomId);
    this.setStatus('waiting');
    const pingMs = this.opts.pingMs ?? PING_MS;
    if (pingMs > 0) this.ping = setInterval(() => this.tick(), pingMs);
  }

  /** Close the room (sends leave when a guest is connected). */
  close(reason: 'quit' | 'gameOver' = 'quit'): void {
    if (this.status === 'closed') return;
    if (this.guestPeer) this.send({ t: 'leave', reason });
    this.clearTimeout();
    if (this.ping) clearInterval(this.ping);
    this.ping = null;
    this.transport.close();
    this.setStatus('closed');
  }

  /** Start the game with the guest who said hello. Returns the host's (full) opening. */
  startGame(): ApplyResult {
    if (!this.guestDeck || this.status !== 'ready') throw new Error('no guest to play with');
    const rand = this.opts.rand ?? cryptoRandom;
    const seed = this.opts.seed ?? Math.floor(rand() * 0x7fffffff);
    const decks: [CardId[], CardId[]] = [secretShuffle(this.opts.deck, rand), secretShuffle(this.guestDeck, rand)];
    const r = newGame({ ...(this.opts.game ?? {}), seed, decks });
    this.session = sessionId(rand);
    this.state = r.state;
    this.seq = 0;
    this.names = [this.opts.name ?? 'HOST', this.guestName];
    this.send({
      t: 'start',
      session: this.session,
      you: GUEST_PLAYER,
      arena: this.opts.arena ?? 'neon',
      names: this.names,
      state: viewFor(r.state, GUEST_PLAYER),
      events: viewEvents(r.events, GUEST_PLAYER),
      legal: this.guestLegal(r.state),
    });
    this.setStatus('playing');
    return r;
  }

  /** The next guest intent waiting (oldest first), or null. */
  takeIntent(): GuestIntent | null {
    return this.intents.shift() ?? null;
  }

  hasIntent(): boolean {
    return this.intents.length > 0;
  }

  /** An action (either player's) was applied to the current state: store it and send the guest its update. */
  commit(result: ApplyResult, actor: PlayerId): void {
    this.state = result.state;
    this.seq++;
    this.send({
      t: 'update',
      seq: this.seq,
      actor,
      events: viewEvents(result.events, GUEST_PLAYER),
      state: viewFor(result.state, GUEST_PLAYER),
      legal: this.guestLegal(result.state),
    });
    if (result.state.winner !== null) this.status = 'over';
  }

  /**
   * Why `intent` must be refused on the current state, or null if it may be applied: it must be the guest's own
   * action, made on the current state (seq), and legal for the engine. A trusted intent (made by the host) passes.
   */
  check(intent: GuestIntent): string | null {
    if (intent.trusted) return null;
    if (!this.state) return 'no game';
    if (intent.action.player !== GUEST_PLAYER) return 'not your player';
    if (intent.seq !== this.seq) return `stale (state ${intent.seq}, host ${this.seq})`;
    if (this.state.winner !== null) return 'the game is over';
    if (!isLegal(this.state, intent.action)) return 'illegal action';
    return null;
  }

  /** The guest's intent was not accepted. */
  refuse(intent: GuestIntent, reason: string): void {
    this.send({ t: 'nack', seq: intent.seq, reason: reason.slice(0, 200) });
  }

  /** Queue an intent made by the host itself (the timeout surrender) for the duel loop. */
  queueIntent(it: GuestIntent): void {
    this.intents.push(it);
    this.onIntent?.();
  }

  /** The surrender the host applies for a guest who did not come back (trusted: no legality check). */
  timeoutSurrender(): GuestIntent {
    return { seq: this.seq, action: { type: 'surrender', player: GUEST_PLAYER }, trusted: true };
  }

  // ------------------------------------------------------------------ internals

  private guestLegal(s: GameState): Action[] | null {
    if (s.winner !== null || actingPlayer(s) !== GUEST_PLAYER) return null;
    return legalActions(s).filter((a) => a.player === GUEST_PLAYER);
  }

  private send(m: NetMessage, peer: string | null = this.guestPeer): void {
    if (peer) this.transport.send(encode(m), peer);
  }

  private receive(text: string, peer: string): void {
    let m: NetMessage;
    try {
      m = decode(text);
    } catch (e) {
      console.warn('[net/host] dropped a malformed message', e);
      return;
    }
    if (m.t === 'hello') return this.hello(m, peer);
    if (peer !== this.guestPeer) return; // only the guest of this room is listened to
    this.lastHeard = Date.now();
    if (this.status === 'disconnected') this.back();
    switch (m.t) {
      case 'action':
        if (this.status !== 'playing') return;
        this.intents.push({ seq: m.seq, action: m.action });
        this.onIntent?.();
        return;
      case 'resync':
        this.snapshot();
        return;
      case 'ping':
        this.send({ t: 'pong', t0: m.t0 });
        return;
      case 'pong':
        this.rtt = Date.now() - m.t0;
        return;
      case 'leave':
        this.guestPeer = null;
        this.clearTimeout();
        if (this.status === 'playing' || this.status === 'disconnected') {
          this.setStatus('over', 'guest left');
          this.onGuestLeft?.();
        } else this.setStatus('waiting', 'guest left');
        return;
      default:
        return; // ack and anything else: nothing to do
    }
  }

  private hello(m: Extract<NetMessage, { t: 'hello' }>, peer: string): void {
    const refuse = (reason: 'protocol' | 'version' | 'deck' | 'full' | 'session', detail?: string) =>
      this.transport.send(encode({ t: 'refuse', reason, detail }), peer);
    if (m.protocol !== PROTOCOL_VERSION) return refuse('protocol', `host protocol ${PROTOCOL_VERSION}, guest ${m.protocol}`);
    if (m.gameVersion !== this.version) return refuse('version', `host ${this.version}, guest ${m.gameVersion}`);
    const inGame = this.status === 'playing' || this.status === 'disconnected';
    if (inGame) {
      // only the guest of this game may come back (same session)
      if (!m.resume || m.resume.session !== this.session) return refuse(this.guestPeer && this.status === 'playing' ? 'full' : 'session');
      this.guestPeer = peer;
      this.lastHeard = Date.now();
      this.transport.send(encode({ t: 'welcome', protocol: PROTOCOL_VERSION, gameVersion: this.version, name: this.names[HOST_PLAYER], session: this.session }), peer);
      this.back();
      this.snapshot();
      return;
    }
    if (this.status === 'over' || this.status === 'closed' || this.status === 'idle') return refuse('full');
    if (this.guestPeer && this.guestPeer !== peer && this.status === 'ready') return refuse('full');
    const check = validateDeck(m.deck);
    if (!check.ok) return refuse('deck', check.issues.map((i) => i.code).join(','));
    this.guestPeer = peer;
    this.lastHeard = Date.now();
    this.guestName = m.name.trim().slice(0, 14) || 'FRIEND';
    this.guestDeck = m.deck as CardId[];
    this.transport.send(encode({ t: 'welcome', protocol: PROTOCOL_VERSION, gameVersion: this.version, name: this.names[HOST_PLAYER], session: '' }), peer);
    this.setStatus('ready');
  }

  private snapshot(): void {
    if (!this.state) return;
    this.send({
      t: 'snapshot',
      session: this.session,
      seq: this.seq,
      you: GUEST_PLAYER,
      arena: this.opts.arena ?? 'neon',
      names: this.names,
      state: viewFor(this.state, GUEST_PLAYER),
      legal: this.guestLegal(this.state),
    });
  }

  private lost(why: string): void {
    if (this.status === 'ready') {
      this.guestPeer = null;
      this.guestDeck = null;
      this.setStatus('waiting', why);
      return;
    }
    if (this.status !== 'playing') return;
    this.setStatus('disconnected', why);
    this.clearTimeout();
    this.timeout = setTimeout(() => {
      this.timeout = null;
      if (this.status !== 'disconnected') return;
      this.status = 'over';
      this.onTimeout?.();
    }, this.opts.disconnectTimeoutMs ?? DISCONNECT_TIMEOUT_MS);
  }

  private back(): void {
    if (this.status !== 'disconnected') return;
    this.clearTimeout();
    this.setStatus('playing', 'guest back');
  }

  private tick(): void {
    if (!this.guestPeer) return;
    this.send({ t: 'ping', t0: Date.now() });
    if (this.status === 'playing' && this.lastHeard && Date.now() - this.lastHeard > SILENCE_MS) this.lost('silence');
  }

  private clearTimeout(): void {
    if (this.timeout) clearTimeout(this.timeout);
    this.timeout = null;
  }

  private setStatus(s: HostStatus, why?: string): void {
    this.status = s;
    this.onStatus?.(s, why);
  }
}

/** Fisher-Yates with the host's secret random (decorrelates uids from the deck list). Fusion Monsters keep their place. */
export function secretShuffle(deck: readonly CardId[], rand: () => number): CardId[] {
  const main = deck.filter((c) => !isFusionMonster(c));
  const fusion = deck.filter((c) => isFusionMonster(c));
  for (let i = main.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [main[i], main[j]] = [main[j], main[i]];
  }
  return [...main, ...fusion];
}

function sessionId(rand: () => number): string {
  let s = '';
  for (let i = 0; i < 12; i++) s += Math.floor(rand() * 36).toString(36);
  return s;
}
